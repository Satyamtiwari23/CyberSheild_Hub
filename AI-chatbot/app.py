@app.route("/auth", methods=["POST"])
def ai_auth():

    token = request.form.get("token", "").strip()

    if not token:

        return redirect(
            "https://satyamtiwari23.github.io/CyberSheild_Hub/login.html"
        )

    decoded = verify_token(token)

    if not decoded:

        return redirect(
            "https://satyamtiwari23.github.io/CyberSheild_Hub/login.html"
        )

    response = make_response(
        redirect("/")
    )

    response.set_cookie(
        "ai_auth_token",
        token,
        httponly=True,
        secure=True,
        samesite="Lax",
        max_age=7 * 24 * 60 * 60
    )

    return response


